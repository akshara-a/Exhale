import React from 'react';
import ReactDOM from 'react-dom/client';
import App from './App.tsx';
import './index.css';

ReactDOM.createRoot(document.getElementById('root')!).render(
  <React.StrictMode>
    <App />
  </React.StrictMode>,
);

// Register Trail-Ready Offline Service Worker
if ('serviceWorker' in navigator && import.meta.env.PROD) {
  window.addEventListener('load', () => {
    navigator.serviceWorker
      .register('/sw.js')
      .then((reg) => {
        console.log('[Exhale] Trail-Ready Offline Service Worker Registered:', reg.scope);
      })
      .catch((err) => {
        console.warn('[Exhale] Service Worker Registration Error:', err);
      });
  });
}
